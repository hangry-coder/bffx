// writeScreenServices emits one `<Screen>ScreenService` per Screen manifest.
// Each service has a single `Get(<Screen>Request) returns (<Screen>Response)`
// RPC; when `spec.stream: true`, a server-streaming `Watch(<Screen>Request)
// returns (stream <Screen>Response)` is also emitted.
//
// Strongly-typed per-Screen services mean each Screen has a distinct gRPC
// method set, which keeps mobile clients fluent (clientV1.UserProfileScreen.Get())
// and lets each screen evolve independently. See plan §5.
func writeScreenServices(sb *strings.Builder, reg *manifest.Registry) {
	for _, s := range reg.Screens {
		var spec manifest.ScreenSpec
		_ = s.UnmarshalSpec(&spec)

		if !grpcAllowedForScreen(spec.Transports) {
			continue
		}

		title := screenProtoTitle(s, &spec)
		sb.WriteString(fmt.Sprintf("service %sScreenService {\n", title))
		sb.WriteString(fmt.Sprintf("  rpc Get(%sRequest) returns (%sResponse);\n", title, title))
		if spec.Stream {
			sb.WriteString(fmt.Sprintf("  rpc Watch(%sRequest) returns (stream %sResponse);\n", title, title))
		}
		sb.WriteString("}\n\n")
	}
}

// writeScreenMessages emits a request/response message pair per Screen.
// Both use google.protobuf.Struct so changes to the source manifest don't
// require regenerating client code. Per-section payloads are surfaced via
// the response's `sections` field.
func writeScreenMessages(sb *strings.Builder, reg *manifest.Registry) {
	for _, s := range reg.Screens {
		var spec manifest.ScreenSpec
		_ = s.UnmarshalSpec(&spec)

		if !grpcAllowedForScreen(spec.Transports) {
			continue
		}

		title := screenProtoTitle(s, &spec)
		sb.WriteString(fmt.Sprintf("message %sRequest {\n", title))
		sb.WriteString("  google.protobuf.Struct params = 1;\n")
		sb.WriteString("}\n\n")

		sb.WriteString(fmt.Sprintf("message %sResponse {\n", title))
		sb.WriteString("  google.protobuf.Struct output = 1;\n")
		sb.WriteString("  map<string, google.protobuf.Struct> sections = 2;\n")
		sb.WriteString("  string version_hash = 3;\n")
		sb.WriteString("  bool killed = 4;\n")
		sb.WriteString("  string kill_reason = 5;\n")
		sb.WriteString("}\n\n")
	}
}

func grpcAllowedForScreen(transports []string) bool {
	if len(transports) == 0 {
		return true
	}
	for _, t := range transports {
		if strings.ToLower(t) == "grpc" {
			return true
		}
	}
	return false
}

// screenProtoTitle returns the TitleCase identifier used to derive the
// `<Title>ScreenService`, `<Title>Request`, and `<Title>Response` symbols
// in the generated proto. Preference order:
//  1. `spec.name` from the manifest (e.g. "Home"           -> "Home"),
//  2. otherwise the auto-derived `metadata.name` minus any trailing
//     `_screen` segment (e.g. "mobile_screens_home_screen" -> "MobileScreensHome").
// Stripping the redundant `_screen` suffix prevents the doubled
// `ScreenScreenService` symbol when teams keep `_screen.yaml` filenames.
func screenProtoTitle(m *manifest.Manifest, spec *manifest.ScreenSpec) string {
	if spec != nil && strings.TrimSpace(spec.Name) != "" {
		return titleCase(spec.Name)
	}
	name := m.Metadata.Name
	if strings.HasSuffix(name, "_screen") {
		name = strings.TrimSuffix(name, "_screen")
	}
	return titleCase(name)
}

func titleCase(s string) string {
	if s == "" {
		return s
	}
	parts := strings.Split(s, "_")
	for i, p := range parts {
		if p == "" {
			continue
		}
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}
