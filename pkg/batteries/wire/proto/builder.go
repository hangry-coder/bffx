func writeResourceMessages(sb *strings.Builder, reg *manifest.Registry) {
	for _, r := range reg.Resources {
		var spec manifest.ResourceSpec
		_ = r.UnmarshalSpec(&spec)

		// Check transport gating
		if len(spec.Transports) > 0 {
			grpcAllowed := false
			for _, t := range spec.Transports {
				if strings.ToLower(t) == "grpc" {
					grpcAllowed = true
					break
				}
			}
			if !grpcAllowed {
				continue
			}
		}

		name := r.Metadata.Name
		sb.WriteString(fmt.Sprintf("message %s {\n", name))
		idx := 1
		// Core ID field
		sb.WriteString(fmt.Sprintf("  string id = %d;\n", idx))
		idx++

		for _, f := range spec.Fields {
			if f.Name == "id" {
				continue
			}
			pbType := mapFieldType(f.Type)
			sb.WriteString(fmt.Sprintf("  %s %s = %d;\n", pbType, f.Name, idx))
			idx++
		}
		sb.WriteString("}\n\n")

		if spec.Routes.Crud {
			sb.WriteString(fmt.Sprintf("message List%ssRequest {\n", name))
			sb.WriteString("  int32 limit = 1;\n")
			sb.WriteString("  int32 offset = 2;\n")
			sb.WriteString("}\n\n")

			sb.WriteString(fmt.Sprintf("message List%ssResponse {\n", name))
			sb.WriteString(fmt.Sprintf("  repeated %s items = 1;\n", name))
			sb.WriteString("  int32 total = 2;\n")
			sb.WriteString("}\n\n")

			sb.WriteString(fmt.Sprintf("message Get%sRequest {\n", name))
			sb.WriteString("  string id = 1;\n")
			sb.WriteString("}\n\n")

			sb.WriteString(fmt.Sprintf("message Create%sRequest {\n", name))
			idx = 1
			for _, f := range spec.Fields {
				if f.Name == "id" {
					continue
				}
				pbType := mapFieldType(f.Type)
				sb.WriteString(fmt.Sprintf("  %s %s = %d;\n", pbType, f.Name, idx))
				idx++
			}
			sb.WriteString("}\n\n")

			sb.WriteString(fmt.Sprintf("message Update%sRequest {\n", name))
			sb.WriteString("  string id = 1;\n")
			idx = 2
			for _, f := range spec.Fields {
				if f.Name == "id" {
					continue
				}
				pbType := mapFieldType(f.Type)
				sb.WriteString(fmt.Sprintf("  %s %s = %d;\n", pbType, f.Name, idx))
				idx++
			}
			sb.WriteString("}\n\n")

			sb.WriteString(fmt.Sprintf("message Delete%sRequest {\n", name))
			sb.WriteString("  string id = 1;\n")
			sb.WriteString("}\n\n")

			sb.WriteString(fmt.Sprintf("message Delete%sResponse {\n", name))
			sb.WriteString("  bool success = 1;\n")
			sb.WriteString("}\n\n")
		}
	}
}

