// BuildProto generates a pure-Go string representing a unified .proto schema
// for all active resources, actions, builders, and pipelines in the registry.
func BuildProto(reg *manifest.Registry, wirePackage string) string {
	if wirePackage == "" {
		wirePackage = "bffx.v1"
	}

	var sb strings.Builder

	// 1. Gather all fields to determine dynamic imports
	hasStruct := false
	hasTimestamp := false

	// Scan resources
	for _, r := range reg.Resources {
		var spec manifest.ResourceSpec
		_ = r.UnmarshalSpec(&spec)
		for _, f := range spec.Fields {
			if f.Type == "json" || f.Type == "map" {
				hasStruct = true
			}
			if f.Type == "date" || f.Type == "datetime" {
				hasTimestamp = true
			}
		}
	}

	// Actions, builders, pipelines, and screens use Struct for loose payloads
	if len(reg.Actions) > 0 || len(reg.Builders) > 0 || len(reg.Pipelines) > 0 || len(reg.Screens) > 0 {
		hasStruct = true
	}

	// 2. Write headers
	sb.WriteString("// Code generated by bffx sync. DO NOT EDIT.\n")
	sb.WriteString("syntax = \"proto3\";\n\n")
	sb.WriteString(fmt.Sprintf("package %s;\n\n", wirePackage))

	// Write package go options
	sb.WriteString("option go_package = \"github.com/hangry-coder/bffx/.bffx/gen/go;bffxv1\";\n\n")

	// Write dynamic imports
	if hasStruct {
		sb.WriteString("import \"google/protobuf/struct.proto\";\n")
	}
	if hasTimestamp {
		sb.WriteString("import \"google/protobuf/timestamp.proto\";\n")
	}
	if hasStruct || hasTimestamp {
		sb.WriteString("\n")
	}

	// 3. Write services
	writeResourceServices(&sb, reg)
	writeActionServices(&sb, reg)
	writeBuilderServices(&sb, reg)
	writePipelineServices(&sb, reg)
	writeScreenServices(&sb, reg)

	// 4. Write messages
	writeResourceMessages(&sb, reg)
	writeActionMessages(&sb, reg)
	writeBuilderMessages(&sb, reg)
	writePipelineMessages(&sb, reg)
	writeScreenMessages(&sb, reg)

	return sb.String()
}

func mapFieldType(t string) string {
	switch t {
	case "string", "text", "email", "uuid":
		return "string"
	case "int":
		return "int64"
	case "float":
		return "double"
	case "bool":
		return "bool"
	case "file":
		return "string"
	case "json", "map":
		return "google.protobuf.Struct"
	case "date", "datetime":
		return "google.protobuf.Timestamp"
	default:
		return "string"
	}
}

func writeResourceServices(sb *strings.Builder, reg *manifest.Registry) {
	for _, r := range reg.Resources {
		var spec manifest.ResourceSpec
		_ = r.UnmarshalSpec(&spec)

		// Check transport gating
		if len(spec.Transports) > 0 {
			grpcAllowed := false
			for _, t := range spec.Transports {
				if strings.ToLower(t) == "grpc" {
					grpcAllowed = true
					break
				}
			}
			if !grpcAllowed {
				continue
			}
		}

		if spec.Routes.Crud {
			name := r.Metadata.Name
			sb.WriteString(fmt.Sprintf("service %sService {\n", name))
			sb.WriteString(fmt.Sprintf("  rpc List%ss(List%ssRequest) returns (List%ssResponse);\n", name, name, name))
			sb.WriteString(fmt.Sprintf("  rpc Get%s(Get%sRequest) returns (%s);\n", name, name, name))
			sb.WriteString(fmt.Sprintf("  rpc Create%s(Create%sRequest) returns (%s);\n", name, name, name))
			sb.WriteString(fmt.Sprintf("  rpc Update%s(Update%sRequest) returns (%s);\n", name, name, name))
			sb.WriteString(fmt.Sprintf("  rpc Delete%s(Delete%sRequest) returns (Delete%sResponse);\n", name, name, name))
			sb.WriteString("}\n\n")
		}
	}
}

